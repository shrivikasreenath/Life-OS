    # Convert defs to 16-byte arrays
    def to_bytes(lines):
        result = []
        for line in lines:
            val = 0
            for i, ch in enumerate(line[:8]):
                if ch == '#':
                    val |= (1 << (7 - i))
            result.append(val)
        while len(result) < 16:
            result.append(0)
        return result[:16]

